void gc9307_draw_char(int x, int y, char c, uint16_t color, uint16_t bg, int scale)
{
    if (c < 32 || c > 126) c = '?';
    int glyph_idx = c - 32;

    for (int col = 0; col < 5; col++) {
        uint8_t line = font5x7[glyph_idx][col];
        for (int row = 0; row < 7; row++) {
            int px = x + col * scale;
            int py = y + row * scale;
            if (line & (1 << row)) {
                gc9307_fill_rect(px, py, scale, scale, color);
            } else if (bg != color) {
                gc9307_fill_rect(px, py, scale, scale, bg);
            }
        }
    }
    // 1-pixel trailing space column
    if (bg != color) {
        gc9307_fill_rect(x + 5 * scale, y, scale, 7 * scale, bg);
    }
}

void gc9307_draw_string(int x, int y, const char *str, uint16_t color, uint16_t bg, int scale)
{
    int cur_x = x;
    while (*str) {
        if (*str == '\n') {
            y += (8 * scale);
            cur_x = x;
        } else {
            gc9307_draw_char(cur_x, y, *str, color, bg, scale);
            cur_x += (6 * scale);
        }
        str++;
    }
}

